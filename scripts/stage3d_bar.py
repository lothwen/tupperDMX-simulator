def vnorm(a) -> np.ndarray:
    a = np.asarray(a, float)
    length = float(np.linalg.norm(a))
    return a if length < 1e-9 else a / length


def translate(x: float, y: float, z: float) -> np.ndarray:
    m = np.eye(4)
    m[:3, 3] = (x, y, z)
    return m


def scale(x: float, y: float, z: float) -> np.ndarray:
    return np.diag([x, y, z, 1.0])


def rot_x(a: float) -> np.ndarray:
    c, s = math.cos(a), math.sin(a)
    m = np.eye(4)
    m[1:3, 1:3] = [[c, -s], [s, c]]
    return m


def rot_z(a: float) -> np.ndarray:
    c, s = math.cos(a), math.sin(a)
    m = np.eye(4)
    m[0:2, 0:2] = [[c, -s], [s, c]]
    return m


def rot_y(a: float) -> np.ndarray:
    """About the world's up axis — which is what a pan motor does."""
    c, s = math.cos(a), math.sin(a)
    m = np.eye(4)
    m[0, 0], m[0, 2], m[2, 0], m[2, 2] = c, s, -s, c
    return m


def align(src, dst) -> np.ndarray:
    """The rotation taking direction `src` onto `dst`."""
    a, b = vnorm(src), vnorm(dst)
    v, c = np.cross(a, b), float(np.dot(a, b))
    m = np.eye(4)
    if np.linalg.norm(v) < 1e-9:
        if c < 0:
            m[:3, :3] = -np.eye(3)
            m[1, 1] = 1.0
        return m
    k = np.array([[0, -v[2], v[1]], [v[2], 0, -v[0]], [-v[1], v[0], 0]])
    m[:3, :3] = np.eye(3) + k + k @ k / (1.0 + c)
    return m


def look_at(eye, forward, up_hint=(0.0, 1.0, 0.0)) -> np.ndarray:
    f = vnorm(forward)
    up = np.asarray(up_hint, float) if abs(f[1]) < 0.98 else np.array([0.0, 0.0, 1.0])
    r = vnorm(np.cross(f, up))
    u = np.cross(r, f)
    m = np.eye(4)
    m[0, :3], m[1, :3], m[2, :3] = r, u, -f
    m[:3, 3] = -m[:3, :3] @ np.asarray(eye, float)
    return m


def perspective(tan_half_y: float, aspect: float, near: float, far: float) -> np.ndarray:
    m = np.zeros((4, 4))
    m[0, 0] = 1.0 / (tan_half_y * aspect)
    m[1, 1] = 1.0 / tan_half_y
    m[2, 2] = (far + near) / (near - far)
    m[2, 3] = 2.0 * far * near / (near - far)
    m[3, 2] = -1.0
    return m


def qmatrix(m: np.ndarray) -> QMatrix4x4:
    return QMatrix4x4(*[float(v) for v in np.asarray(m).ravel()])


def halton(index: int, base: int) -> float:
    """The low-discrepancy sequence the sub-pixel jitter walks."""
    result, fraction = 0.0, 1.0
    while index > 0:
        fraction /= base
        result += fraction * (index % base)
        index //= base
    return result


