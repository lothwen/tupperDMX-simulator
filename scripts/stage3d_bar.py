def slot_index(fdef, cap_type: str, color: Optional[str] = None) -> int:
    """Which DMX slot carries `cap_type` — by capability, never by name."""
    for index, spec in enumerate(fdef.channels):
        if spec.fine_of >= 0:
            continue
        for cap in spec.capabilities:
            if cap.type != cap_type:
                continue
            if color is None or cap.get("color") == color:
                return index
    return -1


def shutter_gate(feature: ShutterFeature, state: FixtureState, now: float) -> float:
    """How open a fixture's shutter is at `now`, 0..1 — the app's own answer,
    across all of OFL's shutter effects, on the same clock-phase waveforms."""
    frame = beam_frame.Frame(state=state, body=None, t=now)
    feature.apply(frame)
    return frame.beam.gate


@dataclass
class Fixture:
    """A lamp on a clamp: its definition, its model, where it hangs, and its
    live state. Its pose is the model's own node hierarchy with the yoke
    panned and the body (or head) tilted — home is straight down, or straight
    up for one standing on its base (`upright`), which is the model turned
    over."""
    key: str
    mode: str
    asset: Asset
    mount: Vec3                    # where the model's origin (the clamp) is
    anchor: Optional[Vec3] = None  # the wall end of a bracket, if it hangs on one
    upright: bool = False          # standing on its base: 2D's hanging=False
    fdef: object = None
    state: Optional[FixtureState] = None
    kind: BeamKind = BeamKind.NONE
    slots: dict = field(default_factory=dict)
    pan: float = 0.0
    tilt: float = 0.0
    scale: float = 1.0
    gate: float = 1.0              # the shutter, this instant

    def resolve(self) -> None:
        self.fdef = resolve_fixture(self.key, self.mode)
        if self.fdef is None:
            raise SystemExit(f"fixture '{self.key}' is not in the library")
        fallback = getattr(renderer_for(self.fdef), "beam_fallback", BeamKind.NONE)
        self.kind = beam_kind(self.fdef, fallback)
        self.slots = {
            "intensity": slot_index(self.fdef, "Intensity"),
            "red": slot_index(self.fdef, "ColorIntensity", "Red"),
            "green": slot_index(self.fdef, "ColorIntensity", "Green"),
            "blue": slot_index(self.fdef, "ColorIntensity", "Blue"),
            "shutter": slot_index(self.fdef, "ShutterStrobe"),
            "pan": slot_index(self.fdef, "Pan"),
            "tilt": slot_index(self.fdef, "Tilt"),
            "zoom": slot_index(self.fdef, "Zoom"),
        }
        # The chassis at the definition's own size: the model says what size
        # it was built at, the definition what size the fixture is.
        built = self.asset.nodes[self.asset.roots[0]].extras.get("dimensions_mm")
        real = self.fdef.physical.dimensions_mm
        if built and real:
            self.scale = float(np.mean([r / b for r, b in zip(real, built)]))
        self._yoke = self.asset.find("yoke")
        self._tilter = max(self.asset.find("body"), self.asset.find("head"))
        self._lens = self.asset.find("lens")
        self._shutter = ShutterFeature(None)
        # DMX 127/128 is home — straight down for a hung head (CLAUDE.md, "The
        # render engine") — so that is what an angle is measured from.
        self.pan_home = self.tilt_home = 0.0
        if self.slots["pan"] >= 0:
            self.pan_home = angle_table(self.fdef, self.slots["pan"], "pan")[128]
        if self.slots["tilt"] >= 0:
            self.tilt_home = angle_table(self.fdef, self.slots["tilt"], "tilt")[128]
        self._slews = (Slew(), Slew())

    def drive(self, dmx: bytes) -> None:
        self.state = resolve_state(self.fdef, dmx)

    def shade(self, now: float) -> None:
        """Where the shutter is in its cycle, this instant."""
        if self.state is not None:
            self.gate = shutter_gate(self._shutter, self.state, now)

    def follow(self, now: float) -> None:
        """Pan and tilt to where the DMX says, with a motor's inertia."""
        if self.state is None or (self.slots["pan"] < 0 and self.slots["tilt"] < 0):
            return
        motion = self.state.motion
        pan_deg = motion.pan_deg if motion.pan_deg is not None else self.pan_home
        tilt_deg = motion.tilt_deg if motion.tilt_deg is not None else self.tilt_home
        pan_slew, tilt_slew = self._slews
        self.pan = math.radians(pan_slew.advance(pan_deg, now, SLEW_TAU) - self.pan_home)
        self.tilt = math.radians(tilt_slew.advance(tilt_deg, now, SLEW_TAU) - self.tilt_home)

    # -- pose ------------------------------------------------------------
    def orientation(self) -> np.ndarray:
        """The model's turn and size, about its clamp."""
        turn = rot_z(math.pi) if self.upright else np.eye(4)
        return turn @ scale(self.scale, self.scale, self.scale)

    def root(self) -> np.ndarray:
        return translate(*self.mount) @ self.orientation()

    def pose(self) -> List[np.ndarray]:
        nodes = self.asset.nodes
        return self.asset.world(self.root(), {
            self._yoke: nodes[self._yoke].matrix @ rot_y(self.pan),
            self._tilter: nodes[self._tilter].matrix @ rot_x(-self.tilt),
        })

    def aim(self) -> np.ndarray:
        return vnorm(self.pose()[self._tilter][:3, :3] @ np.array([0.0, -1.0, 0.0]))

    def point_at(self, target) -> None:
        """Pan and tilt so the beam passes through `target`. The tilt pivot
        sits on the pan axis, so pan cannot move it and one solve is exact."""
        pivot = self.pose()[self._tilter][:3, 3]
        d = vnorm(np.asarray(target, float) - pivot)
        self.tilt = math.acos(max(-1.0, min(1.0, -d[1])))
        self.pan = math.atan2(d[0], d[2])

    # -- light -----------------------------------------------------------
    def half_angle_deg(self) -> float:
        """The live cone half-angle. A zoom channel wins, as in the draft; a
        surface light (`beam_kind` said NONE) throws no shaft but still lights
        the room through its lens, which `resting_half_angle` reads as a wash."""
        zoom = self.state.optics.zoom_deg if self.state else None
        if zoom is not None:
            return max(1.0, zoom) / 2.0
        half = resting_half_angle(self.fdef, self.kind)
        if half is None:
            half = resting_half_angle(self.fdef, BeamKind.WASH) or 60.0
        return min(half, 85.0)

    def emitter(self, output: float) -> Emitter:
        """This fixture as a light. A dark fixture keeps its slot with no
        colour, so every lens keeps pointing at the same light."""
        pose = self.pose()
        rgb = (0.0, 0.0, 0.0)
        state = self.state
        if state is not None and self.gate > 0.0:
            rgb = tuple(c * output * self.gate for c in linear_rgb(state.scaled_rgb()))
        half = self.half_angle_deg()
        inner_scale = 0.8 if self.kind is BeamKind.HARD else 0.3
        lens_radius = self.asset.nodes[self.asset.roots[0]].extras.get("lens_radius", 0.05)
        return Emitter(
            position=tuple(pose[self._lens][:3, 3]),
            direction=tuple(vnorm(pose[self._tilter][:3, :3] @ np.array([0.0, -1.0, 0.0]))),
            rgb=rgb,
            cos_outer=math.cos(math.radians(half)),
            cos_inner=math.cos(math.radians(half * inner_scale)),
            radius=lens_radius * self.scale,
        )


def angle_table(fdef, slot: int, axis: str) -> List[float]:
    """What every byte on one motion channel means, according to the app."""
    table = []
    for value in range(256):
        frame = bytearray(fdef.channel_count)
        frame[slot] = value
        motion = resolve_state(fdef, bytes(frame)).motion
        angle = motion.pan_deg if axis == "pan" else motion.tilt_deg
        table.append(angle if angle is not None else 0.0)
    return table


def nearest_byte(table: List[float], degrees: float) -> int:
    return min(range(256), key=lambda value: abs(table[value] - degrees))


class Rig:
    """The photograph's lighting as real fixtures on the venue's pipes."""

    FRONT_XS = (-1.8, -0.9, 0.0, 0.9, 1.8)
    HEAD_XS = (-1.6, 1.6)

    def __init__(self, assets: Dict[str, Asset], venue: Venue):
        can, head = assets["par_can"], assets["moving_head"]
        W = venue.half_width
        front_y, front_z = venue.pipes["front"]
        back_y, back_z = venue.pipes["back"]
        foh_y, foh_z = venue.pipes["foh"]
        # The five cans across the top of the photograph, nearly straight down,
        # so their pools land between the backline and the lip.
        self.front = [Fixture("par-rgbw", "6ch", can, (x, front_y, front_z)) for x in self.FRONT_XS]
        # The two lamps high on the side walls, out on brackets, grazing the
        # brick: the scallops down both walls in the photo.
        self.grazers = [Fixture("par-rgbw", "6ch", can, (side * (W - 0.7), 3.22, -2.0),
                                anchor=(side * W, 3.22, -2.0)) for side in (-1.0, 1.0)]
        # The photograph lights its backline from the front, yet every lamp it
        # shows is overhead and facing the camera: in a real room that light
        # comes from a front-of-house pipe over the audience, out of frame.
        self.foh = [Fixture("par-rgbw", "6ch", can, (x, foh_y, foh_z)) for x in (-1.4, 1.4)]
        # The two small lamps low on the drape's border are the backlight:
        # heads, because a hard beam is what shows up in a bar's haze.
        self.heads = [Fixture("moving-head", "12ch", head, (x, back_y, back_z)) for x in self.HEAD_XS]
        for fixture in self.cans() + self.heads:
            fixture.resolve()

        for fixture in self.front:
            fixture.point_at((fixture.mount[0] * 0.8, 0.0, -0.9))
        for fixture in self.grazers:
            fixture.point_at((math.copysign(W, fixture.mount[0]), 0.5, -1.4))
        for fixture in self.foh:
            fixture.point_at((fixture.mount[0] * 0.3, 0.7, -2.0))

        # The house look crosses the heads onto the front of the deck, so the
        # two shafts meet over the mic stand.
        self.head_targets = [(0.55, 0.0, -0.55), (-0.55, 0.0, -0.55)]
        first = self.heads[0]
        self.pan_table = angle_table(first.fdef, first.slots["pan"], "pan")
        self.tilt_table = angle_table(first.fdef, first.slots["tilt"], "tilt")
        self.pan_home = first.pan_home
        self.tilt_home = first.tilt_home
        self.sweeping = False
        # Off unless asked for: the show's patch is the rig now, and this one
        # would light the stage over whatever the show is doing.
        self.enabled = False

    def cans(self) -> List[Fixture]:
        return self.front + self.grazers + self.foh

    def fixtures(self) -> List[Fixture]:
        """In emitter order: a fixture's index here is its light's index."""
        return self.cans() + self.heads

    # -- the house look ------------------------------------------------
    # Tungsten-warm white throughout, as in the photograph: roughly 3000 K
    # from the pars, a touch cooler from the heads' discharge-white.
    def tick(self, t: float) -> None:
        for fixture in self.front:
            fixture.drive(self._par_dmx(fixture, 205, (255, 180, 110)))
        for fixture in self.grazers:
            fixture.drive(self._par_dmx(fixture, 225, (255, 172, 98)))
        for fixture in self.foh:
            fixture.drive(self._par_dmx(fixture, 255, (255, 185, 118)))
        now = time.monotonic()
        for index, head in enumerate(self.heads):
            head.drive(self._head_dmx(index, t))
            head.follow(now)

    def _par_dmx(self, fixture: Fixture, intensity: int, rgb) -> bytes:
        frame = bytearray(fixture.fdef.channel_count)
        # Warm white from the RGB emitters alone: this par folds its white
        # channel in additively and clamps, so any W at all reads as pure white.
        self._put(frame, fixture.slots, intensity=intensity, red=rgb[0], green=rgb[1], blue=rgb[2])
        return bytes(frame)

    def _head_dmx(self, index: int, t: float) -> bytes:
        head = self.heads[index]
        pivot = head.pose()[head._tilter][:3, 3]
        d = vnorm(np.asarray(self.head_targets[index]) - pivot)
        pan = self.pan_home + math.degrees(math.atan2(d[0], d[2]))
        tilt = self.tilt_home + math.degrees(math.acos(max(-1.0, min(1.0, -d[1]))))
        if self.sweeping:
            phase = index * math.pi
            pan += 24.0 * math.sin(t * 0.35 + phase)
            tilt += 9.0 * math.sin(t * 0.23 + phase + 0.8)
        frame = bytearray(head.fdef.channel_count)
        self._put(frame, head.slots,
                  pan=nearest_byte(self.pan_table, pan), tilt=nearest_byte(self.tilt_table, tilt),
                  intensity=190,
                  # 240-255 is Open on this fixture; 255 is NOT "on" in general.
                  shutter=250,
                  red=255, green=205, blue=160, zoom=70)
        return bytes(frame)

    @staticmethod
    def _put(frame: bytearray, slots: dict, **values) -> None:
        for name, value in values.items():
            index = slots.get(name, -1)
            if 0 <= index < len(frame):
                frame[index] = max(0, min(255, int(value)))

    # -- what the renderer needs ---------------------------------------
    def emitters(self) -> List[Emitter]:
        """Always all eleven, in `fixtures()` order — the pars' lenses are baked
        into the room with their light's index — and dark when switched off."""
        lights = ([f.emitter(PAR_OUTPUT) for f in self.cans()]
                  + [f.emitter(HEAD_OUTPUT) for f in self.heads])
        if self.enabled:
            return lights
        return [dataclasses.replace(light, rgb=(0.0, 0.0, 0.0)) for light in lights]


