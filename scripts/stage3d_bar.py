class OrbitCamera:
    """An orbit round a focus point, kept inside the room and above its floors."""

    def __init__(self, venue: Venue):
        self.venue = venue
        self.reset()

    def reset(self) -> None:
        self.focus: Vec3 = PHOTO_VIEW["focus"]
        self.yaw = PHOTO_VIEW["yaw"]
        self.pitch = PHOTO_VIEW["pitch"]
        self.radius = PHOTO_VIEW["radius"]

    def _inside(self, point, margin: float) -> Vec3:
        v = self.venue
        x = max(-v.half_width + margin, min(v.half_width - margin, point[0]))
        z = max(v.curtain_z + 0.2 + margin, min(v.rear_wall - margin, point[2]))
        floor = 0.0 if z < 0.1 else -v.deck_height        # the deck is a riser
        y = max(floor + margin, min(v.ceiling - margin, point[1]))
        return (x, y, z)

    def position(self) -> Vec3:
        horizontal = math.cos(self.pitch) * self.radius
        offset = (math.sin(self.yaw) * horizontal, math.sin(self.pitch) * self.radius,
                  math.cos(self.yaw) * horizontal)
        return self._inside(np.asarray(self.focus) + offset, 0.3)

    def basis(self):
        position = np.asarray(self.position())
        forward = vnorm(np.asarray(self.focus) - position)
        right = vnorm(np.cross(forward, (0.0, 1.0, 0.0)))
        up = np.cross(right, forward)
        return tuple(position), tuple(right), tuple(up), tuple(forward)

    def walk(self, forward_step: float, side_step: float, up_step: float) -> None:
        forward = vnorm(np.asarray(self.focus) - np.asarray(self.position()))
        flat = vnorm((forward[0], 0.0, forward[2]))
        side = vnorm(np.cross(flat, (0.0, 1.0, 0.0)))
        moved = np.asarray(self.focus) + flat * forward_step + side * side_step + (0.0, up_step, 0.0)
        self.focus = self._inside(moved, 0.4)


