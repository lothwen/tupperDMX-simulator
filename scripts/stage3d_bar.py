_GL_TRIANGLES = 0x0004
_GL_TRIANGLE_STRIP = 0x0005
_GL_FLOAT = 0x1406
_GL_DEPTH_TEST = 0x0B71
_GL_LESS = 0x0201
_GL_LEQUAL = 0x0203
_GL_COLOR_BUFFER_BIT = 0x4000
_GL_DEPTH_BUFFER_BIT = 0x0100
_GL_SCISSOR_TEST = 0x0C11
_GL_BLEND = 0x0BE2
_GL_CULL_FACE = 0x0B44
_GL_CONSTANT_ALPHA = 0x8003
_GL_ONE_MINUS_CONSTANT_ALPHA = 0x8004
_GL_TEXTURE0 = 0x84C0
_GL_TEXTURE_2D = 0x0DE1
_GL_FRAMEBUFFER = 0x8D40
_GL_RGBA32F = 0x8814
_GL_R32F = 0x822E

VERTEX_FLOATS = 13          # position 3, normal 3, uv 2, colour 4, emitter 1
SHADOW_NEAR, SHADOW_FAR = 0.05, 25.0


@dataclass
class Batch:
    """Triangles uploaded for one material: a VAO and how many vertices."""
    material: Material
    textures: Tuple[object, object, object]      # base, normal, metallic-roughness
    vao: object
    vbo: object
    count: int


def expand_primitive(prim: Primitive, world: np.ndarray, emitter: int) -> np.ndarray:
    """One primitive as de-indexed interleaved vertices in `world` space."""
    idx = prim.indices.ravel()
    positions = prim.positions[idx] @ world[:3, :3].T + world[:3, 3]
    normals = prim.normals[idx] @ np.linalg.inv(world[:3, :3])
    normals /= np.maximum(np.linalg.norm(normals, axis=1, keepdims=True), 1e-12)
    out = np.empty((len(idx), VERTEX_FLOATS), np.float32)
    out[:, 0:3] = positions
    out[:, 3:6] = normals
    out[:, 6:8] = prim.uvs[idx]
    out[:, 8:12] = prim.colors[idx]
    out[:, 12] = emitter + 1
    return out


class BarRenderer:
    """Owns the GL objects. Knows nothing about widgets, so a script can drive
    it into an offscreen framebuffer exactly as the window does."""

    def __init__(self, stage: Stage):
        self.stage = stage
        self.gl = None
        self.programs = {}
        self.static_batches: List[Batch] = []
        self._parts: Dict[str, List[Tuple[int, Batch]]] = {}    # asset -> (node index, batch)
        self._cells: Dict[str, list] = {}                       # key -> [texture, shape, bytes]
        self.casters = None
        self.caster_count = 0
        self.frame_fbo = self.accum_fbo = self.atlas = None
        self.size = (0, 0)
        self.samples = 0
        self._signature = None
        self._tiles: Dict[int, tuple] = {}
        self._locations: Dict[Tuple[str, str], int] = {}
        self._textures: Dict[Tuple[str, int, bool], object] = {}
        self._keep = []

    # -- setup -----------------------------------------------------------
    def initialize(self, context) -> Optional[str]:
        from PyQt6.QtOpenGL import (QOpenGLBuffer, QOpenGLShader, QOpenGLShaderProgram,
                                    QOpenGLVersionFunctionsFactory, QOpenGLVersionProfile,
                                    QOpenGLVertexArrayObject)
        if context is None or context.isOpenGLES():
            return "no desktop OpenGL context"
        profile = QOpenGLVersionProfile()
        profile.setVersion(4, 1)
        profile.setProfile(QSurfaceFormat.OpenGLContextProfile.CoreProfile)
        self.gl = QOpenGLVersionFunctionsFactory.get(profile, context)
        if self.gl is None:
            return "no OpenGL 4.1 core functions"
        self.gl.initializeOpenGLFunctions()

        for name, vertex, fragment in (
                ("lit", MESH_VERTEX, expand(LIT_FRAGMENT)),
                ("shadow", SHADOW_VERTEX, SHADOW_FRAGMENT),
                ("post", FULLSCREEN_VERTEX, expand(POST_FRAGMENT)),
                ("resolve", FULLSCREEN_VERTEX, RESOLVE_FRAGMENT)):
            program = QOpenGLShaderProgram()
            if not program.addShaderFromSourceCode(QOpenGLShader.ShaderTypeBit.Vertex, vertex):
                return f"{name} vertex shader: {program.log()}"
            if not program.addShaderFromSourceCode(QOpenGLShader.ShaderTypeBit.Fragment, fragment):
                return f"{name} fragment shader: {program.log()}"
            if not program.link():
                return f"{name} link: {program.log()}"
            self.programs[name] = program

        self._QBuffer, self._QVao = QOpenGLBuffer, QOpenGLVertexArrayObject
        corners = np.array([-1, -1, 1, -1, -1, 1, 1, 1], np.float32)
        self.quad = self._upload(corners, [(0, 2, 0)], 8)
        self._white = self._solid_texture((255, 255, 255, 255))
        self._build_scene()
        return None

    def _upload(self, data: np.ndarray, layout, stride: int):
        """A VAO over one interleaved buffer; `layout` is (location, size, offset)."""
        vao = self._QVao()
        vao.create()
        vao.bind()
        vbo = self._QBuffer(self._QBuffer.Type.VertexBuffer)
        vbo.create()
        vbo.bind()
        raw = np.ascontiguousarray(data, np.float32).tobytes()
        vbo.allocate(raw, len(raw))
        program = self.programs["lit"]
        for location, size, offset in layout:
            program.enableAttributeArray(location)
            program.setAttributeBuffer(location, _GL_FLOAT, offset, size, stride)
        vao.release()
        vbo.release()
        self._keep.append((vao, vbo))
        return vao

    def _solid_texture(self, rgba):
        from PyQt6.QtOpenGL import QOpenGLTexture
        image = QImage(1, 1, QImage.Format.Format_RGBA8888)
        image.fill(QColor(*rgba))
        texture = QOpenGLTexture(image)
        self._keep.append(texture)
        return texture

    def _texture(self, asset: Asset, image: int, srgb: bool):
        """A GLB image as a mipmapped, repeating GL texture. Base colour is
        stored sRGB-encoded (glTF says so) and decoded by the sampler."""
        from PyQt6.QtOpenGL import QOpenGLTexture
        key = (asset.name, image, srgb)
        if key in self._textures:
            return self._textures[key]
        img = QImage.fromData(asset.images[image]).convertToFormat(QImage.Format.Format_RGBA8888)
        texture = QOpenGLTexture(QOpenGLTexture.Target.Target2D)
        texture.setFormat(QOpenGLTexture.TextureFormat.SRGB8_Alpha8 if srgb
                          else QOpenGLTexture.TextureFormat.RGBA8_UNorm)
        texture.setSize(img.width(), img.height())
        texture.setMipLevels(texture.maximumMipLevels())
        texture.allocateStorage(QOpenGLTexture.PixelFormat.RGBA, QOpenGLTexture.PixelType.UInt8)
        bits = img.constBits()
        bits.setsize(img.sizeInBytes())
        texture.setData(QOpenGLTexture.PixelFormat.RGBA, QOpenGLTexture.PixelType.UInt8, bits)
        texture.generateMipMaps()
        texture.setMinMagFilters(QOpenGLTexture.Filter.LinearMipMapLinear, QOpenGLTexture.Filter.Linear)
        texture.setWrapMode(QOpenGLTexture.WrapMode.Repeat)
        texture.setMaximumAnisotropy(8.0)
        self._textures[key] = texture
        return texture

    def _batch(self, asset: Asset, material: Material, vertices: np.ndarray) -> Batch:
        layout = [(0, 3, 0), (1, 3, 12), (2, 2, 24), (3, 4, 32), (4, 1, 48)]
        vao = self._upload(vertices, layout, VERTEX_FLOATS * 4)
        textures = (
            self._texture(asset, material.base_image, True) if material.base_image >= 0 else None,
            self._texture(asset, material.normal_image, False) if material.normal_image >= 0 else None,
            self._texture(asset, material.mr_image, False) if material.mr_image >= 0 else None)
        return Batch(material, textures, vao, None, len(vertices))

    def _build_scene(self) -> None:
        """Bake every static placement into world space, merged by material.
        What moves is uploaded part by part on first use (`_parts_for`)."""
        stage = self.stage
        merged: Dict[str, Tuple[Asset, Material, List[np.ndarray]]] = {}
        casters: List[np.ndarray] = []
        for placement in stage.statics:
            asset = stage.assets[placement.asset]
            worlds = stage.static_pose(placement)
            for index, node in enumerate(asset.nodes):
                if node.mesh is None:
                    continue
                shadows = asset.casts_shadows(index)
                for prim in asset.meshes[node.mesh]:
                    material = asset.materials[prim.material]
                    emitter = placement.light if material.name == "lens" else -1
                    vertices = expand_primitive(prim, worlds[index], emitter)
                    merged.setdefault(material.name, (asset, material, []))[2].append(vertices)
                    if shadows:
                        casters.append(vertices[:, 0:3])
        for asset, material, chunks in merged.values():
            self.static_batches.append(self._batch(asset, material, np.concatenate(chunks)))
        positions = np.concatenate(casters)
        self.casters = self._upload(positions, [(0, 3, 0)], 12)
        self.caster_count = len(positions)
        print(f"stage3d_bar: {len(self.static_batches)} static batches, "
              f"{sum(b.count for b in self.static_batches) // 3} triangles, "
              f"{self.caster_count // 3} shadow casters")

    def _parts_for(self, name: str) -> List[Tuple[int, Batch]]:
        """A model's parts in their own node space, to be posed per frame."""
        if name not in self._parts:
            asset = self.stage.assets[name]
            self._parts[name] = [(index, self._batch(asset, asset.materials[prim.material],
                                                     expand_primitive(prim, np.eye(4), -1)))
                                 for index, node in enumerate(asset.nodes) if node.mesh is not None
                                 for prim in asset.meshes[node.mesh]]
        return self._parts[name]

    def _upload_cells(self, frame: Frame) -> None:
        """Each fixture's cells as a float texture, one texel a cell, sampled
        exactly (no filtering): re-sent only when a cell has changed."""
        from PyQt6.QtOpenGL import QOpenGLTexture
        for body in frame.bodies:
            cells = body.cells
            if cells is None:
                continue
            rows, columns = cells.image.shape[:2]
            entry = self._cells.get(cells.key)
            if entry is None or entry[1] != (rows, columns):
                texture = QOpenGLTexture(QOpenGLTexture.Target.Target2D)
                texture.setFormat(QOpenGLTexture.TextureFormat.RGBA32F)
                texture.setSize(columns, rows)
                texture.allocateStorage(QOpenGLTexture.PixelFormat.RGBA, QOpenGLTexture.PixelType.Float32)
                texture.setMinMagFilters(QOpenGLTexture.Filter.Nearest, QOpenGLTexture.Filter.Nearest)
                texture.setWrapMode(QOpenGLTexture.WrapMode.ClampToEdge)
                entry = [texture, (rows, columns), None]
                self._cells[cells.key] = entry
            rgba = np.ones((rows, columns, 4), np.float32)
            rgba[..., :3] = cells.image * CELL_GAIN
            raw = rgba.tobytes()
            if raw != entry[2]:
                entry[0].setData(QOpenGLTexture.PixelFormat.RGBA, QOpenGLTexture.PixelType.Float32,
                                 sip.voidptr(raw))
                entry[2] = raw

    def _ensure_targets(self, width: int, height: int) -> None:
        from PyQt6.QtOpenGL import QOpenGLFramebufferObject, QOpenGLFramebufferObjectFormat
        if self.atlas is None:
            fmt = QOpenGLFramebufferObjectFormat()
            fmt.setAttachment(QOpenGLFramebufferObject.Attachment.Depth)
            fmt.setInternalTextureFormat(_GL_R32F)
            side = SHADOW_TILE * ATLAS_TILES
            self.atlas = QOpenGLFramebufferObject(side, side, fmt)
            self._tiles.clear()
        if self.size == (width, height):
            return
        fmt = QOpenGLFramebufferObjectFormat()
        fmt.setAttachment(QOpenGLFramebufferObject.Attachment.Depth)
        fmt.setInternalTextureFormat(_GL_RGBA32F)
        self.frame_fbo = QOpenGLFramebufferObject(width, height, fmt)
        plain = QOpenGLFramebufferObjectFormat()
        # 32-bit float: the running average divides by the sample count, and a
        # half float would lose the last samples' contribution to rounding.
        plain.setInternalTextureFormat(_GL_RGBA32F)
        self.accum_fbo = QOpenGLFramebufferObject(width, height, plain)
        self.size = (width, height)
        self.samples = 0

    # -- per frame -------------------------------------------------------
    def render(self, frame: Frame, width: int, height: int, target_fbo: int) -> None:
        gl = self.gl
        # Every state the passes rely on, set here rather than assumed: a
        # QOpenGLWidget hands paintGL whatever Qt last left enabled.
        gl.glDisable(_GL_BLEND)
        gl.glDisable(_GL_SCISSOR_TEST)
        gl.glDisable(_GL_CULL_FACE)
        gl.glDisable(_GL_DEPTH_TEST)
        gl.glDepthMask(True)
        gl.glColorMask(True, True, True, True)

        self._ensure_targets(width, height)
        signature = frame.signature()
        if signature != self._signature:
            self._signature = signature
            self.samples = 0

        if self.samples < MAX_SAMPLES or frame.fog.drifting():
            self.samples += 1
            light_views = self._update_atlas(frame)
            self._scene_pass(frame, width, height, light_views)
            self._post_pass(frame, width, height, light_views)

        gl.glBindFramebuffer(_GL_FRAMEBUFFER, target_fbo)
        gl.glViewport(0, 0, width, height)
        program = self.programs["resolve"]
        program.bind()
        gl.glActiveTexture(_GL_TEXTURE0)
        gl.glBindTexture(_GL_TEXTURE_2D, self.accum_fbo.texture())
        program.setUniformValue("u_accum", 0)
        program.setUniformValue("u_exposure", float(frame.exposure))
        program.setUniformValue("u_resolution", float(width), float(height))
        self._draw_quad()
        program.release()

    def _light_view(self, emitter: Emitter) -> Tuple[np.ndarray, float]:
        """A spot's shadow camera: down its axis, a little wider than its cone."""
        half = math.acos(max(-1.0, min(1.0, emitter.cos_outer))) + math.radians(5.0)
        tan_half = math.tan(min(half, math.radians(80.0)))
        view = look_at(emitter.position, emitter.direction)
        return perspective(tan_half, 1.0, SHADOW_NEAR, SHADOW_FAR) @ view, tan_half

    def _update_atlas(self, frame: Frame) -> List[Tuple[np.ndarray, float]]:
        """Re-render the tiles of the spots that moved; the rest are reused."""
        gl = self.gl
        views = []
        for index, emitter in enumerate(frame.emitters[:MAX_SHADOWS]):
            if not emitter.shadows:
                break
            views.append(self._light_view(emitter))
        program = self.programs["shadow"]
        bound = False
        for index, (vp, _tan) in enumerate(views):
            emitter = frame.emitters[index]
            key = _quantise((emitter.position, emitter.direction, emitter.cos_outer))
            if self._tiles.get(index) == key:
                continue
            if not bound:
                self.atlas.bind()
                gl.glEnable(_GL_DEPTH_TEST)
                gl.glDepthFunc(_GL_LESS)
                gl.glEnable(_GL_SCISSOR_TEST)
                program.bind()
                bound = True
            x = (index % ATLAS_TILES) * SHADOW_TILE
            y = (index // ATLAS_TILES) * SHADOW_TILE
            gl.glViewport(x, y, SHADOW_TILE, SHADOW_TILE)
            gl.glScissor(x, y, SHADOW_TILE, SHADOW_TILE)
            gl.glClearColor(1.0e6, 1.0e6, 1.0e6, 1.0e6)
            gl.glClear(_GL_COLOR_BUFFER_BIT | _GL_DEPTH_BUFFER_BIT)
            program.setUniformValue("u_vp", qmatrix(vp))
            program.setUniformValue("u_origin", QVector3D(*[float(c) for c in emitter.position]))
            self.casters.bind()
            gl.glDrawArrays(_GL_TRIANGLES, 0, self.caster_count)
            self.casters.release()
            self._tiles[index] = key
        if bound:
            program.release()
            gl.glDisable(_GL_SCISSOR_TEST)
            gl.glDisable(_GL_DEPTH_TEST)
        return views

    def _loc(self, program_name: str, name: str) -> int:
        key = (program_name, name)
        location = self._locations.get(key)
        if location is None:
            location = self.programs[program_name].uniformLocation(name)
            self._locations[key] = location
        return location

    def _set_lights(self, program_name: str, frame: Frame, light_views) -> None:
        program = self.programs[program_name]

        def vec3(name, v):
            program.setUniformValue(self._loc(program_name, name), QVector3D(*[float(c) for c in v]))

        program.setUniformValue(self._loc(program_name, "u_light_count"), len(frame.emitters))
        for i, emitter in enumerate(frame.emitters):
            vec3(f"u_light_pos[{i}]", emitter.position)
            vec3(f"u_light_dir[{i}]", emitter.direction)
            vec3(f"u_light_rgb[{i}]", emitter.rgb)
            program.setUniformValue(self._loc(program_name, f"u_light_shape[{i}]"),
                                    QVector4D(float(emitter.cos_outer), float(emitter.cos_inner),
                                              float(emitter.radius), 1.0 if emitter.air else 0.0))
        program.setUniformValue(self._loc(program_name, "u_shadow_count"), len(light_views))
        for i, (vp, tan_half) in enumerate(light_views):
            program.setUniformValue(self._loc(program_name, f"u_light_vp[{i}]"), qmatrix(vp))
            program.setUniformValue(self._loc(program_name, f"u_light_tan[{i}]"), float(tan_half))
        # Wrapped: while the air drifts `samples` never stops counting, and a
        # hash fed ever larger floats loses its low bits and turns to pattern.
        program.setUniformValue(self._loc(program_name, "u_seed"), float(self.samples % 1024))
        program.setUniformValue(self._loc(program_name, "u_fog_density"), float(frame.fog.density))
        program.setUniformValue(self._loc(program_name, "u_fog_height"), float(frame.fog.height))

    def _jitter(self) -> Tuple[float, float]:
        # Halton (2, 3) over the pixel: sample 1 is the pixel centre, so a view
        # that moves every frame is still sampled where it always was.
        index = self.samples - 1
        return (halton(index, 2) - 0.5, halton(index, 3) - 0.5) if index else (0.0, 0.0)

    def _scene_pass(self, frame: Frame, width: int, height: int, light_views) -> None:
        gl = self.gl
        position, right, up, forward = (np.asarray(v, float) for v in frame.camera)
        jx, jy = self._jitter()
        view = np.eye(4)
        view[0, :3], view[1, :3], view[2, :3] = right, up, -forward
        view[:3, 3] = -view[:3, :3] @ position
        # The jitter as a clip-space shift: the post pass casts its rays
        # through the same sub-pixel offset, so its haze lines up exactly.
        shift = np.eye(4)
        shift[0, 3], shift[1, 3] = -2.0 * jx / width, -2.0 * jy / height
        view_proj = shift @ perspective(frame.tan_half_fov, width / height, 0.03, 40.0) @ view

        self.frame_fbo.bind()
        gl.glViewport(0, 0, width, height)
        gl.glClearColor(0.0, 0.0, 0.0, 1.0e6)
        gl.glClear(_GL_COLOR_BUFFER_BIT | _GL_DEPTH_BUFFER_BIT)
        gl.glEnable(_GL_DEPTH_TEST)

        program = self.programs["lit"]
        program.bind()
        program.setUniformValue(self._loc("lit", "u_view_proj"), qmatrix(view_proj))
        program.setUniformValue(self._loc("lit", "u_cam_pos"), QVector3D(*[float(c) for c in position]))
        for name, unit in (("u_atlas", 0), ("u_base_tex", 1), ("u_normal_tex", 2), ("u_mr_tex", 3),
                           ("u_cells_tex", 4)):
            program.setUniformValue(self._loc("lit", name), unit)
        self._set_lights("lit", frame, light_views)
        program.setUniformValue(self._loc("lit", "u_bounce_count"), len(frame.bounces))
        for i, bounce in enumerate(frame.bounces):
            for name, value in (("pos", bounce.position), ("nrm", bounce.normal), ("rgb", bounce.rgb)):
                program.setUniformValue(self._loc("lit", f"u_bounce_{name}[{i}]"),
                                        QVector3D(*[float(c) for c in value]))
        gl.glActiveTexture(_GL_TEXTURE0)
        gl.glBindTexture(_GL_TEXTURE_2D, self.atlas.texture())

        self._upload_cells(frame)
        draws = [(batch, np.eye(4), -1, None) for batch in self.static_batches]
        for body in frame.bodies:
            draws += [(batch, body.matrices[node], body.light, body.cells)
                      for node, batch in self._parts_for(body.asset)]

        # Depth first, then shade what survived: each pixel is lit once.
        gl.glDepthFunc(_GL_LESS)
        gl.glColorMask(False, False, False, False)
        program.setUniformValue(self._loc("lit", "u_depth_only"), True)
        for batch, model, light, cells in draws:
            self._draw(program, batch, model, light, cells, textured=False)
        gl.glDepthFunc(_GL_LEQUAL)
        gl.glDepthMask(False)
        gl.glColorMask(True, True, True, True)
        program.setUniformValue(self._loc("lit", "u_depth_only"), False)
        for batch, model, light, cells in draws:
            self._draw(program, batch, model, light, cells, textured=True)
        gl.glDepthMask(True)
        gl.glDisable(_GL_DEPTH_TEST)
        program.release()

    def _draw(self, program, batch: Batch, model: np.ndarray, light: int,
              cells: Optional[CellsView], textured: bool) -> None:
        program.setUniformValue(self._loc("lit", "u_model"), qmatrix(model))
        if textured:
            m = batch.material
            loc = lambda name: self._loc("lit", name)
            program.setUniformValue(loc("u_base_color"), QVector4D(*[float(c) for c in m.base_color]))
            program.setUniformValue(loc("u_metallic"), float(m.metallic))
            program.setUniformValue(loc("u_roughness"), float(m.roughness))
            program.setUniformValue(loc("u_emission"), QVector3D(*[float(c) for c in m.emission]))
            program.setUniformValue(loc("u_sheen"), QVector3D(*[float(c) for c in m.sheen]))
            program.setUniformValue(loc("u_normal_scale"), float(m.normal_scale))
            program.setUniformValue(loc("u_draw_emitter"), int(light if m.name == "lens" else -1))
            for unit, (flag, texture) in enumerate(zip(("u_has_base", "u_has_normal", "u_has_mr"),
                                                       batch.textures), start=1):
                program.setUniformValue(loc(flag), texture is not None)
                (texture or self._white).bind(unit)
            lit_cells = cells is not None and m.name == "cells"
            program.setUniformValue(loc("u_has_cells"), lit_cells)
            if lit_cells:
                self._cells[cells.key][0].bind(4)
                program.setUniformValue(loc("u_cells_origin"), float(cells.origin[0]), float(cells.origin[1]))
                program.setUniformValue(loc("u_cells_grid"), float(cells.grid[0]), float(cells.grid[1]))
                program.setUniformValue(loc("u_cells_dot"), QVector3D(*[float(c) for c in cells.dot]))
            else:
                self._white.bind(4)
        batch.vao.bind()
        self.gl.glDrawArrays(_GL_TRIANGLES, 0, batch.count)
        batch.vao.release()

    def _post_pass(self, frame: Frame, width: int, height: int, light_views) -> None:
        gl = self.gl
        self.accum_fbo.bind()
        gl.glViewport(0, 0, width, height)
        # Running average: the n-th sample weighs 1/n against what is there,
        # or never less than 1/DRIFT_HISTORY while the air moves under it.
        # The first is written, not blended: a new float buffer is whatever
        # memory it was given, and 0 x NaN is still NaN.
        if self.samples > 1:
            weight = 1.0 / self.samples
            if frame.fog.drifting():
                weight = max(weight, 1.0 / DRIFT_HISTORY)
            gl.glEnable(_GL_BLEND)
            gl.glBlendFunc(_GL_CONSTANT_ALPHA, _GL_ONE_MINUS_CONSTANT_ALPHA)
            gl.glBlendColor(0.0, 0.0, 0.0, weight)
        program = self.programs["post"]
        program.bind()
        gl.glActiveTexture(_GL_TEXTURE0)
        gl.glBindTexture(_GL_TEXTURE_2D, self.frame_fbo.texture())
        gl.glActiveTexture(_GL_TEXTURE0 + 1)
        gl.glBindTexture(_GL_TEXTURE_2D, self.atlas.texture())
        program.setUniformValue(self._loc("post", "u_frame"), 0)
        program.setUniformValue(self._loc("post", "u_atlas"), 1)
        self._set_lights("post", frame, light_views)
        jx, jy = self._jitter()
        position, right, up, forward = frame.camera
        for name, value in (("u_cam_pos", position), ("u_cam_right", right), ("u_cam_up", up),
                            ("u_cam_fwd", forward)):
            program.setUniformValue(self._loc("post", name), QVector3D(*[float(c) for c in value]))
        program.setUniformValue(self._loc("post", "u_resolution"), float(width), float(height))
        program.setUniformValue(self._loc("post", "u_jitter"), float(jx), float(jy))
        program.setUniformValue(self._loc("post", "u_tan_half_fov"), float(frame.tan_half_fov))
        program.setUniformValue(self._loc("post", "u_fog_texture"), float(frame.fog.texture))
        program.setUniformValue(self._loc("post", "u_fog_g"), float(frame.fog.forward))
        for name, value in (("u_fog_drift", frame.drifted), ("u_fog_ambient", frame.air_ambient)):
            program.setUniformValue(self._loc("post", name), QVector3D(*[float(c) for c in value]))
        self._draw_quad()
        program.release()
        gl.glActiveTexture(_GL_TEXTURE0)
        gl.glDisable(_GL_BLEND)

    def _draw_quad(self) -> None:
        self.quad.bind()
        self.gl.glDrawArrays(_GL_TRIANGLE_STRIP, 0, 4)
        self.quad.release()


def build_frame(stage: Stage, camera: OrbitCamera, fog: Fog, drifted: Vec3,
                exposure: float) -> Frame:
    """What the renderer needs from the rigs, the camera and the air, this instant.

    The light list's order is load-bearing. The house rig comes first and
    always all of it, because its pars' lenses are baked into the room with
    their light's index; every shadowed light comes before every unshadowed
    one, because the atlas hands out tiles from the front until the first
    light that wants none; and the pixel spill comes last, so it is what a
    list too long for the shaders loses."""
    rig, patch = stage.rig, stage.patch
    house_rig = rig.emitters()
    spots = patch.spots()
    emitters = (house_rig + spots + stage.house + patch.surface_lights())[:MAX_LIGHTS]
    first_head = len(rig.cans())
    bodies = [BodyDraw("moving_head", head.pose(), first_head + index) for index, head in enumerate(rig.heads)]
    bodies += patch.draws(len(house_rig), len(emitters))
    if patch.machines:
        fog = dataclasses.replace(fog, density=fog.density + patch.atmosphere.level * SMOKE_DENSITY)
    return Frame(camera=camera.basis(), tan_half_fov=math.tan(math.radians(FOV_VERTICAL_DEG) * 0.5),
                 emitters=emitters, bounces=bounce_lights(stage.venue, house_rig + spots), bodies=bodies,
                 fog=fog, air_ambient=air_ambient(stage.venue, fog, emitters), drifted=drifted,
                 exposure=exposure)


