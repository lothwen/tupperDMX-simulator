class Stage:
    """The venue, the set pieces, the audience, the bar, the house rig and the
    show's patch."""

    def __init__(self, patch: Sequence[FixtureInstance] = ()):
        self.assets = load_assets()
        self.venue = Venue.from_asset(self.assets["venue"])
        self.rig = Rig(self.assets, self.venue)
        self.patch = PatchRig(self.assets, self.venue, patch)
        v = self.venue

        statics = [Placement("venue", np.eye(4))]
        statics += [Placement(name, translate(*position)) for name, position in PROPS]
        rng = np.random.default_rng(7)          # nobody lines chairs up with a ruler
        for row in range(CHAIR_ROWS):
            for col in range(CHAIR_COLS):
                x = (col - 0.5 * (CHAIR_COLS - 1)) * CHAIR_DX + rng.uniform(-0.025, 0.025)
                z = CHAIR_Z0 + row * CHAIR_DZ + rng.uniform(-0.04, 0.04)
                statics.append(Placement("chair", translate(x, -v.deck_height, z)
                                         @ rot_y(rng.uniform(-0.12, 0.12))))
        statics.append(Placement("bar", translate(BAR_X, -v.deck_height, v.rear_wall - BAR_FROM_REAR)))
        # The pars never move, so they are baked in with the room; only the
        # heads are drawn part by part.
        for index, fixture in enumerate(self.rig.cans()):
            statics.append(Placement("par_can", fixture.root(), light=index))
            if fixture.anchor is not None:
                reach = np.asarray(fixture.mount) - np.asarray(fixture.anchor)
                statics.append(Placement("wall_arm", translate(*fixture.anchor) @ align((1, 0, 0), reach)
                                         @ scale(float(np.linalg.norm(reach)), 1.0, 1.0)))
        # The patch's rigging — pipe stubs and wall arms — never moves either.
        statics += self.patch.statics
        self.statics = statics
        self.house = self._house_lights()
        lights = (len(self.rig.fixtures()) + len(self.patch.spots()) + len(self.house)
                  + len(self.patch.surface_lights()))
        if lights > MAX_LIGHTS:
            print(f"stage3d_bar: {lights} lights for {MAX_LIGHTS} slots — the last "
                  f"{lights - MAX_LIGHTS} (pixel spill first) are dropped", file=sys.stderr)

    def static_pose(self, placement: Placement) -> List[np.ndarray]:
        if placement.asset == "par_can":
            fixture = self.rig.cans()[placement.light]
            return fixture.pose()
        return self.assets[placement.asset].world(placement.matrix)

    def _house_lights(self) -> List[Emitter]:
        """The lamps the assets carry: KHR_lights_punctual spots, placed."""
        lit, unshadowed = [], []
        for placement in self.statics:
            asset = self.assets[placement.asset]
            if not asset.lights:
                continue
            worlds = asset.world(placement.matrix)
            for index, node in enumerate(asset.nodes):
                if node.light is None:
                    continue
                light = asset.lights[node.light]
                spot = light.get("spot", {})
                outer = spot.get("outerConeAngle", math.pi / 4)
                inner = spot.get("innerConeAngle", 0.0)
                emitter = Emitter(
                    position=tuple(worlds[index][:3, 3]),
                    direction=tuple(vnorm(worlds[index][:3, :3] @ np.array([0.0, 0.0, -1.0]))),
                    rgb=tuple(c * light.get("intensity", 1.0) for c in light.get("color", (1, 1, 1))),
                    cos_outer=math.cos(outer), cos_inner=math.cos(inner),
                    radius=node.extras.get("lens_radius", 0.05),
                    shadows=node.extras.get("cast_shadows", True))
                (lit if emitter.shadows else unshadowed).append(emitter)
        return lit + unshadowed


