HUD_STYLE = ("color: #e8ecf4; background: rgba(0,0,0,150); padding: 8px 10px;"
             "font-family: monospace; font-size: 11px; border-radius: 4px;")

# One slider per `Fog` field: its range, and how its value reads.
FOG_CONTROLS = (
    ("density", 0.0, 0.4, "{:.3f} /m"),
    ("height", 0.3, 8.0, "{:.1f} m"),
    ("texture", 0.0, 1.0, "{:.2f}"),
    ("drift", 0.0, 0.6, "{:.2f} m/s"),
    ("forward", 0.0, 0.9, "{:.2f}"),
)


class FogPanel(QWidget):
    """The air's controls. Every move of a slider is a new `Fog`."""

    STEPS = 400

    def __init__(self, parent: QWidget):
        super().__init__(parent)
        self.fog = Fog()
        self.setAttribute(Qt.WidgetAttribute.WA_StyledBackground)
        self.setStyleSheet(f"FogPanel {{ {HUD_STYLE} }} QLabel {{ color: #e8ecf4;"
                           " font-family: monospace; font-size: 11px; }")
        grid = QGridLayout(self)
        grid.setContentsMargins(10, 8, 10, 8)
        grid.addWidget(QLabel("fog    [F] hides"), 0, 0, 1, 3)
        self._rows = {}
        for row, (name, low, high, form) in enumerate(FOG_CONTROLS, start=1):
            slider = QSlider(Qt.Orientation.Horizontal)
            slider.setRange(0, self.STEPS)
            slider.setFixedWidth(140)
            # Keys stay with the view: WASD walks, it does not nudge a slider.
            slider.setFocusPolicy(Qt.FocusPolicy.NoFocus)
            readout = QLabel(form.format(getattr(self.fog, name)))
            readout.setMinimumWidth(72)
            grid.addWidget(QLabel(name), row, 0)
            grid.addWidget(slider, row, 1)
            grid.addWidget(readout, row, 2)
            self._rows[name] = (slider, readout, low, high, form)
            slider.setValue(self._step(name, getattr(self.fog, name)))
            slider.valueChanged.connect(lambda step, name=name: self._moved(name, step))
        self.adjustSize()

    def nudge(self, name: str, delta: float) -> None:
        self._rows[name][0].setValue(self._step(name, getattr(self.fog, name) + delta))

    def _step(self, name: str, value: float) -> int:
        _slider, _readout, low, high, _form = self._rows[name]
        return round((min(high, max(low, value)) - low) / (high - low) * self.STEPS)

    def _moved(self, name: str, step: int) -> None:
        _slider, readout, low, high, form = self._rows[name]
        value = low + (high - low) * step / self.STEPS
        self.fog = dataclasses.replace(self.fog, **{name: value})
        readout.setText(form.format(value))


class BarView(QOpenGLWidget):
    """The window: a camera, a stage, a renderer, a DMX feed and a read-out."""

    def __init__(self, stage: Stage, feed: Optional[stage3d_patch.DmxFeed] = None,
                 patch_source: str = ""):
        super().__init__()
        self.stage = stage
        self.feed = feed
        self.patch_source = patch_source
        if feed is not None:
            feed.frame.connect(stage.patch.update_dmx)
        self.camera = OrbitCamera(stage.venue)
        self.renderer = BarRenderer(stage)
        self.failed = False
        self._drag = None

        self.exposure = 1.0
        self.show_time = 0.0
        self._sweep_started: Optional[float] = None
        # Where the drift has carried the air: integrated, not speed x time,
        # so moving the drift slider changes the pace without a jump.
        self.drifted: Vec3 = (0.0, 0.0, 0.0)
        self._last_tick = time.monotonic()

        self.setFocusPolicy(Qt.FocusPolicy.StrongFocus)
        self.setMinimumSize(720, 460)
        self.hud = QLabel(self)
        self.hud.setStyleSheet(HUD_STYLE)
        self.hud.move(12, 12)
        self.fog_panel = FogPanel(self)

        self._last_paint: Optional[float] = None
        self.fps = 0.0

        # 60 Hz while anything moves; once a still view has converged the scene
        # pass is skipped and each tick costs one texture blit.
        self.timer = QTimer(self)
        self.timer.timeout.connect(self._tick)
        self.timer.start(16)

    def _tick(self) -> None:
        now = time.monotonic()
        if self._sweep_started is not None:
            self.show_time = now - self._sweep_started
        step = self.fog_panel.fog.drift * (now - self._last_tick)
        self.drifted = tuple(d + w * step for d, w in zip(self.drifted, WIND))
        self._last_tick = now
        self.stage.rig.tick(self.show_time)
        self.stage.patch.tick(now)
        self._update_hud()
        self.update()

    def _update_hud(self) -> None:
        rig = self.stage.rig
        fog = self.fog_panel.fog
        if fog.drifting():
            state = f"last {DRIFT_HISTORY} (air drifting)"
        else:
            samples = self.renderer.samples
            state = f"{samples:3d}/{MAX_SAMPLES}{' (still)' if samples >= MAX_SAMPLES else ''}"
        patch = self.stage.patch
        smoke = patch.atmosphere.level * SMOKE_DENSITY if patch.machines else 0.0
        dmx = self.feed.describe() if self.feed is not None else "none"
        keys = "drag orbit | wheel dolly | WASD walk | Q/E down/up | [ ] fog | F fog panel | - = exposure"
        keys += " | H house rig | space sweep | R photo view"
        if self.feed is not None and self.feed.controller is not None:
            keys += " | N next scene | B blackout"
        self.hud.setText(
            f"{self.fps:5.1f} fps   samples {state}"
            f"   fog {fog.density:.3f}/m + smoke {smoke:.3f}   exposure {self.exposure:.2f}\n"
            f"patch {self.patch_source}: {patch.summary()}, on the upstage rig line\n"
            f"dmx   {dmx}\n"
            f"house rig {'on' if rig.enabled else 'off'}: 9 x par-rgbw, 2 x {rig.heads[0].key}"
            f"   sweep {'on' if rig.sweeping else 'off'}\n"
            f"{keys}")
        self.hud.adjustSize()

    def resizeEvent(self, event) -> None:
        super().resizeEvent(event)
        self.fog_panel.move(self.width() - self.fog_panel.width() - 12, 12)

    def initializeGL(self) -> None:
        why = self.renderer.initialize(QOpenGLContext.currentContext())
        if why is not None:
            print(f"stage3d_bar: cannot render ({why})", file=sys.stderr)
            self.failed = True
            return
        version = QOpenGLContext.currentContext().format()
        print(f"stage3d_bar: OpenGL {version.majorVersion()}.{version.minorVersion()} ready")

    def paintGL(self) -> None:
        if self.failed:
            return
        started = time.perf_counter()
        if self._last_paint is not None:
            elapsed = started - self._last_paint
            if elapsed > 1e-6:
                self.fps = 1.0 / elapsed if self.fps <= 0.0 else self.fps * 0.9 + 0.1 / elapsed
        self._last_paint = started
        ratio = self.devicePixelRatioF()
        width = max(1, int(self.width() * ratio))
        height = max(1, int(self.height() * ratio))
        frame = build_frame(self.stage, self.camera, self.fog_panel.fog, self.drifted, self.exposure)
        self.renderer.render(frame, width, height, self.defaultFramebufferObject())

    # -- interaction ----------------------------------------------------
    def mousePressEvent(self, event) -> None:
        self._drag = event.position()

    def mouseMoveEvent(self, event) -> None:
        if self._drag is None:
            return
        delta = event.position() - self._drag
        self._drag = event.position()
        self.camera.yaw -= delta.x() * 0.006
        self.camera.pitch = max(-1.3, min(1.3, self.camera.pitch + delta.y() * 0.005))

    def mouseReleaseEvent(self, event) -> None:
        self._drag = None

    def wheelEvent(self, event) -> None:
        factor = 0.9 if event.angleDelta().y() > 0 else 1.1
        self.camera.radius = max(0.6, min(12.0, self.camera.radius * factor))

    def keyPressEvent(self, event) -> None:
        key = event.key()
        step = 0.3
        rig = self.stage.rig
        if key == Qt.Key.Key_Escape:
            self.window().close()
        elif key == Qt.Key.Key_H:
            rig.enabled = not rig.enabled
        elif key == Qt.Key.Key_N and self.feed is not None:
            self.feed.next_scene()
        elif key == Qt.Key.Key_B and self.feed is not None:
            self.feed.blackout()
        elif key == Qt.Key.Key_Space:
            rig.sweeping = not rig.sweeping
            self._sweep_started = time.monotonic() - self.show_time if rig.sweeping else None
        elif key == Qt.Key.Key_R:
            self.camera.reset()
        elif key == Qt.Key.Key_BracketLeft:
            self.fog_panel.nudge("density", -0.01)
        elif key == Qt.Key.Key_BracketRight:
            self.fog_panel.nudge("density", 0.01)
        elif key == Qt.Key.Key_F:
            self.fog_panel.setVisible(not self.fog_panel.isVisible())
        elif key == Qt.Key.Key_Minus:
            self.exposure = max(0.1, self.exposure - 0.1)
        elif key in (Qt.Key.Key_Equal, Qt.Key.Key_Plus):
            self.exposure = min(6.0, self.exposure + 0.1)
        elif key == Qt.Key.Key_W:
            self.camera.walk(step, 0.0, 0.0)
        elif key == Qt.Key.Key_S:
            self.camera.walk(-step, 0.0, 0.0)
        elif key == Qt.Key.Key_A:
            self.camera.walk(0.0, -step, 0.0)
        elif key == Qt.Key.Key_D:
            self.camera.walk(0.0, step, 0.0)
        elif key == Qt.Key.Key_Q:
            self.camera.walk(0.0, 0.0, -step)
        elif key == Qt.Key.Key_E:
            self.camera.walk(0.0, 0.0, step)
        else:
            super().keyPressEvent(event)


def main() -> int:
    parser = argparse.ArgumentParser(description="The bar, in 3D, lit by a show's patch from DMX.")
    parser.add_argument("--show", help="a .show folder (default: the one the app last opened)")
    parser.add_argument("--dmx", choices=("artnet", "local"), default="artnet",
                        help="artnet: listen for a running TupperDMX; local: run its "
                             "software controller in here (N steps the scenes)")
    parser.add_argument("--port", type=int, help="Art-Net port (default: the app's)")
    parser.add_argument("--universe", type=int, help="Art-Net universe (default: the app's)")
    parser.add_argument("--house-rig", action="store_true",
                        help="start with the photograph's own pars and heads on")
    args = parser.parse_args()

    # As stage/gpu/layer.py's configure_surface_format(): force desktop GL or a
    # Wayland/EGL session hands out GL ES, and do NOT ask for a version.
    fmt = QSurfaceFormat()
    fmt.setAlphaBufferSize(8)
    fmt.setDepthBufferSize(24)
    fmt.setRenderableType(QSurfaceFormat.RenderableType.OpenGL)
    QSurfaceFormat.setDefaultFormat(fmt)

    app = QApplication(sys.argv[:1])
    source, patch = stage3d_patch.load_patch(args.show)
    stage = Stage(patch)
    stage.rig.enabled = args.house_rig
    print(f"stage3d_bar: patch from {source}: {stage.patch.summary()}; "
          f"{len(stage.statics)} placements, {len(stage.house)} house lights")

    port, universe = stage3d_patch.artnet_settings()
    feed = stage3d_patch.DmxFeed(args.dmx, patch, args.port or port,
                                 universe if args.universe is None else args.universe)
    app.aboutToQuit.connect(feed.stop)
    if args.dmx == "local":
        feed.next_scene()                 # something to look at straight away

    view = BarView(stage, feed, source)
    view.setWindowTitle("TupperDMX — the bar, in 3D")
    view.resize(1280, 800)
    view.show()
    return app.exec()


if __name__ == "__main__":
    raise SystemExit(main())
