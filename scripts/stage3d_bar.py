@dataclass
class Material:
    name: str
    base_color: Tuple[float, float, float, float] = (1.0, 1.0, 1.0, 1.0)
    metallic: float = 1.0
    roughness: float = 1.0
    emission: Tuple[float, float, float] = (0.0, 0.0, 0.0)     # HDR, strength applied
    sheen: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    base_image: int = -1
    normal_image: int = -1
    mr_image: int = -1
    normal_scale: float = 1.0


@dataclass
class Primitive:
    positions: np.ndarray
    normals: np.ndarray
    uvs: np.ndarray
    colors: np.ndarray
    indices: np.ndarray
    material: int


@dataclass
class GltfNode:
    name: str
    matrix: np.ndarray
    mesh: Optional[int] = None
    children: List[int] = field(default_factory=list)
    extras: dict = field(default_factory=dict)
    light: Optional[int] = None


@dataclass
class Asset:
    """One GLB, parsed: CPU-side arrays only, so the rig can read a fixture's
    pivots before any GL context exists."""
    name: str
    nodes: List[GltfNode]
    roots: List[int]
    meshes: List[List[Primitive]]
    materials: List[Material]
    images: List[bytes]
    lights: List[dict]
    extras: dict

    def find(self, name: str) -> int:
        for index, node in enumerate(self.nodes):
            if node.name == name:
                return index
        return -1

    def world(self, root: np.ndarray, overrides: Optional[Dict[int, np.ndarray]] = None) -> List[np.ndarray]:
        """Every node's world matrix under `root`; `overrides` replaces a
        node's local matrix — how a yoke is panned and a head tilted."""
        out: List[Optional[np.ndarray]] = [None] * len(self.nodes)
        overrides = overrides or {}

        def walk(index: int, parent: np.ndarray) -> None:
            out[index] = parent @ overrides.get(index, self.nodes[index].matrix)
            for child in self.nodes[index].children:
                walk(child, out[index])

        for index in self.roots:
            walk(index, root)
        return out

    def bounds(self, root: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
        """The corners of the box round every mesh at rest under `root`."""
        worlds = self.world(root)
        points = [prim.positions @ worlds[index][:3, :3].T + worlds[index][:3, 3]
                  for index, node in enumerate(self.nodes) if node.mesh is not None
                  for prim in self.meshes[node.mesh]]
        stacked = np.concatenate(points)
        return stacked.min(axis=0), stacked.max(axis=0)

    def casts_shadows(self, index: int) -> bool:
        """A node's `cast_shadows` extra, inherited from its ancestors."""
        parents = {child: i for i, node in enumerate(self.nodes) for child in node.children}
        while index is not None:
            flag = self.nodes[index].extras.get("cast_shadows")
            if flag is not None:
                return bool(flag)
            index = parents.get(index)
        return True


_COMPONENTS = {5120: np.int8, 5121: np.uint8, 5122: np.int16, 5123: np.uint16,
               5125: np.uint32, 5126: np.float32}
_WIDTHS = {"SCALAR": 1, "VEC2": 2, "VEC3": 3, "VEC4": 4, "MAT4": 16}


def load_glb(path: str) -> Asset:
    """The subset of glTF 2.0 the bar's assets use — which is most of it:
    indexed triangles, PBR metallic-roughness with textures, node hierarchies,
    COLOR_0, KHR_lights_punctual, emissive strength and sheen."""
    with open(path, "rb") as fh:
        data = fh.read()
    magic, _version, _length = struct.unpack_from("<III", data, 0)
    if magic != 0x46546C67:
        raise ValueError(f"{path}: not a GLB")
    offset, gltf, binary = 12, None, b""
    while offset < len(data):
        size, kind = struct.unpack_from("<II", data, offset)
        chunk = data[offset + 8:offset + 8 + size]
        if kind == 0x4E4F534A:
            gltf = json.loads(chunk)
        elif kind == 0x004E4942:
            binary = chunk
        offset += 8 + size

    def view_bytes(index: int) -> bytes:
        view = gltf["bufferViews"][index]
        start = view.get("byteOffset", 0)
        return binary[start:start + view["byteLength"]]

    def accessor(index: int) -> np.ndarray:
        acc = gltf["accessors"][index]
        view = gltf["bufferViews"][acc["bufferView"]]
        dtype = np.dtype(_COMPONENTS[acc["componentType"]])
        width = _WIDTHS[acc["type"]]
        start = view.get("byteOffset", 0) + acc.get("byteOffset", 0)
        stride = view.get("byteStride", width * dtype.itemsize)
        if stride == width * dtype.itemsize:
            flat = np.frombuffer(binary, dtype, acc["count"] * width, start)
            array = flat.reshape(acc["count"], width) if width > 1 else flat
        else:
            raw = np.frombuffer(binary, np.uint8, acc["count"] * stride, start).reshape(acc["count"], stride)
            array = raw[:, :width * dtype.itemsize].copy().view(dtype).reshape(acc["count"], width)
        if acc.get("normalized") and dtype != np.float32:
            array = array.astype(np.float32) / np.iinfo(dtype).max
        return np.asarray(array, np.float32 if dtype == np.float32 or acc.get("normalized") else array.dtype)

    textures = gltf.get("textures", [])

    def image_of(ref: Optional[dict]) -> int:
        return textures[ref["index"]]["source"] if ref else -1

    materials = []
    for record in gltf.get("materials", []):
        pbr = record.get("pbrMetallicRoughness", {})
        ext = record.get("extensions", {})
        strength = ext.get("KHR_materials_emissive_strength", {}).get("emissiveStrength", 1.0)
        materials.append(Material(
            name=record.get("name", ""),
            base_color=tuple(pbr.get("baseColorFactor", (1.0, 1.0, 1.0, 1.0))),
            metallic=pbr.get("metallicFactor", 1.0),
            roughness=pbr.get("roughnessFactor", 1.0),
            emission=tuple(c * strength for c in record.get("emissiveFactor", (0.0, 0.0, 0.0))),
            sheen=tuple(ext.get("KHR_materials_sheen", {}).get("sheenColorFactor", (0.0, 0.0, 0.0))),
            base_image=image_of(pbr.get("baseColorTexture")),
            normal_image=image_of(record.get("normalTexture")),
            mr_image=image_of(pbr.get("metallicRoughnessTexture")),
            normal_scale=record.get("normalTexture", {}).get("scale", 1.0)))
    if not materials:
        materials.append(Material("default"))

    meshes = []
    for record in gltf.get("meshes", []):
        primitives = []
        for prim in record["primitives"]:
            if prim.get("mode", 4) != 4:
                continue
            attrs = prim["attributes"]
            positions = accessor(attrs["POSITION"])
            count = len(positions)
            indices = (accessor(prim["indices"]).astype(np.int64).reshape(-1, 3) if "indices" in prim
                       else np.arange(count).reshape(-1, 3))
            if "NORMAL" in attrs:
                normals = accessor(attrs["NORMAL"])
            else:
                normals = np.zeros_like(positions)
                face = np.cross(positions[indices[:, 1]] - positions[indices[:, 0]],
                                positions[indices[:, 2]] - positions[indices[:, 0]])
                for k in range(3):
                    np.add.at(normals, indices[:, k], face)
            uvs = accessor(attrs["TEXCOORD_0"]) if "TEXCOORD_0" in attrs else np.zeros((count, 2), np.float32)
            if "COLOR_0" in attrs:
                colors = accessor(attrs["COLOR_0"])
                if colors.shape[1] == 3:
                    colors = np.concatenate([colors, np.ones((count, 1), np.float32)], 1)
            else:
                colors = np.ones((count, 4), np.float32)
            primitives.append(Primitive(positions, normals, uvs, colors, indices, prim.get("material", 0)))
        meshes.append(primitives)

    nodes = []
    for record in gltf.get("nodes", []):
        if "matrix" in record:
            matrix = np.array(record["matrix"], float).reshape(4, 4).T
        else:
            matrix = np.eye(4)
            tx, ty, tz = record.get("translation", (0.0, 0.0, 0.0))
            qx, qy, qz, qw = record.get("rotation", (0.0, 0.0, 0.0, 1.0))
            sx, sy, sz = record.get("scale", (1.0, 1.0, 1.0))
            rotation = np.array([
                [1 - 2 * (qy * qy + qz * qz), 2 * (qx * qy - qz * qw), 2 * (qx * qz + qy * qw)],
                [2 * (qx * qy + qz * qw), 1 - 2 * (qx * qx + qz * qz), 2 * (qy * qz - qx * qw)],
                [2 * (qx * qz - qy * qw), 2 * (qy * qz + qx * qw), 1 - 2 * (qx * qx + qy * qy)]])
            matrix[:3, :3] = rotation * np.array([sx, sy, sz])
            matrix[:3, 3] = (tx, ty, tz)
        light = record.get("extensions", {}).get("KHR_lights_punctual", {}).get("light")
        nodes.append(GltfNode(record.get("name", ""), matrix, record.get("mesh"),
                              list(record.get("children", [])), record.get("extras", {}), light))

    scene = gltf.get("scenes", [{}])[gltf.get("scene", 0)]
    return Asset(
        name=os.path.splitext(os.path.basename(path))[0],
        nodes=nodes, roots=list(scene.get("nodes", [])), meshes=meshes, materials=materials,
        images=[view_bytes(image["bufferView"]) for image in gltf.get("images", [])],
        lights=gltf.get("extensions", {}).get("KHR_lights_punctual", {}).get("lights", []),
        extras=scene.get("extras", {}))


def load_assets() -> Dict[str, Asset]:
    names = ["venue", "chair", "bar", "par_can", "moving_head", "wall_arm"] + [p[0] for p in PROPS]
    assets = {}
    for name in names:
        path = os.path.join(ASSET_DIR, f"{name}.glb")
